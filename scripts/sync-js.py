"""Build self-contained package copies from the owned shared JavaScript source."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
source=(root/'sdk/shared/contracts.mjs').read_text()
names=re.findall(r'export (?:async )?(?:class|function|const) (\w+)',source)
(root/'sdk/web/shared.mjs').write_text(source)
(root/'sdk/nodejs/shared.cjs').write_text('// Generated by scripts/sync-js.py.\n'+source.replace('export ','')+'\nmodule.exports = {'+', '.join(names)+'};\n')
